/* Ambil teks TRIMMED (spasi/baris baru di ujung tetap dipertahankan di luar)
   dan kembalikan versi Inggrisnya kalau ada & currentLang==='en', selain itu
   kembalikan aslinya apa adanya (termasuk saat currentLang==='id'). */
function t(s){
  if(currentLang !== 'en') return s;
  return Object.prototype.hasOwnProperty.call(I18N_EN, s) ? I18N_EN[s] : s;
}

/* Menerjemahkan DOM statis (dipakai sekali saat load, hanya kalau
   currentLang==='en') — jalan TreeWalker atas node TEXT di dalam `root`,
   ganti hanya bagian TRIMMED dari tiap node yang persis cocok dengan key
   I18N_EN (supaya whitespace/indentasi template asli tetap terjaga), lalu
   terjemahkan juga atribut placeholder/aria-label/title tiap elemen yang
   nilainya persis cocok dengan sebuah key. */
function translateStaticDOM(root){
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, null);
  const textNodes = [];
  let node;
  while((node = walker.nextNode())) textNodes.push(node);
  textNodes.forEach(n=>{
    const raw = n.nodeValue;
    const trimmed = raw.trim();
    if(!trimmed) return;
    if(!Object.prototype.hasOwnProperty.call(I18N_EN, trimmed)) return;
    const translated = I18N_EN[trimmed];
    const start = raw.indexOf(trimmed);
    if(start === -1) return;
    n.nodeValue = raw.slice(0, start) + translated + raw.slice(start + trimmed.length);
  });

  const ATTRS = ['placeholder', 'aria-label', 'title', 'data-placeholder'];
  const all = root.querySelectorAll('*');
  all.forEach(el=>{
    ATTRS.forEach(attr=>{
      if(!el.hasAttribute(attr)) return;
      const val = el.getAttribute(attr);
      const trimmed = val.trim();
      if(trimmed && Object.prototype.hasOwnProperty.call(I18N_EN, trimmed)){
        el.setAttribute(attr, I18N_EN[trimmed]);
      }
    });
  });
}

if(currentLang === 'en'){
  document.documentElement.lang = 'en';
  translateStaticDOM(document.body);
} else {
  document.documentElement.lang = 'id';
}

/* Tombol pilih bahasa di layar login (pojok kanan atas, kelihatan sebelum
   sempat login) -- disorot sesuai currentLang begitu halaman dimuat. Panel
   Bahasa di Pengaturan (untuk yang sudah login) punya pasangan tombol sendiri
   dengan id berbeda (langBtnId/langBtnEn), disorot lewat openSettingsSub(). */
(function highlightAuthLangButtons(){
  const btnId = document.getElementById('authLangBtnId');
  const btnEn = document.getElementById('authLangBtnEn');
  if(btnId) btnId.classList.toggle('active', currentLang === 'id');
  if(btnEn) btnEn.classList.toggle('active', currentLang === 'en');
})();

/* Ganti bahasa tampilan lalu reload — cara termudah & paling aman untuk
   memastikan SELURUH halaman (termasuk konten yang sudah dirender JS sejak
   load) konsisten satu bahasa, tanpa perlu kamus balik (en->id) atau
   MutationObserver yang mengintersepsi setiap render ulang. */
function setLanguage(lang){
  try{ localStorage.setItem('nk_lang', lang); }catch(e){}
  location.reload();
}
